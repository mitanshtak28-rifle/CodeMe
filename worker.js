// CodeMe free AI backend — Cloudflare Workers AI
// In the Worker dashboard, add a Workers AI binding named: AI
// Add secret CODEME_ACCESS_TOKEN. Add variable ALLOWED_ORIGIN with your
// published GitHub Pages origin, e.g. https://YOURNAME.github.io
const MODEL = "@cf/meta/llama-3.1-8b-instruct";

export default {
  async fetch(request, env) {
    const origin = request.headers.get("Origin") || "";
    const allowedOrigin = env.ALLOWED_ORIGIN || "";
    const cors = {
      "Access-Control-Allow-Origin": allowedOrigin && origin === allowedOrigin ? origin : "null",
      "Vary": "Origin",
      "Access-Control-Allow-Methods": "POST, OPTIONS",
      "Access-Control-Allow-Headers": "Content-Type, Authorization",
      "Access-Control-Max-Age": "86400"
    };
    if (request.method === "OPTIONS") return new Response(null, { status: 204, headers: cors });
    if (new URL(request.url).pathname !== "/generate") return out({ error: "Use /generate" }, 404, cors);
    if (request.method !== "POST") return out({ error: "POST required" }, 405, cors);
    if (!allowedOrigin || origin !== allowedOrigin) return out({ error: "Origin not allowed. Configure ALLOWED_ORIGIN." }, 403, cors);
    if (!env.AI || !env.CODEME_ACCESS_TOKEN) return out({ error: "Add the AI binding and CODEME_ACCESS_TOKEN secret in Worker settings." }, 503, cors);
    const auth = request.headers.get("Authorization") || "";
    if (auth !== "Bearer " + env.CODEME_ACCESS_TOKEN) return out({ error: "Invalid access token." }, 401, cors);

    let input;
    try { input = await request.json(); } catch { return out({ error: "Invalid JSON" }, 400, cors); }
    const prompt = String(input.prompt || "").trim().slice(0, 5000);
    if (prompt.length < 5) return out({ error: "Prompt too short" }, 400, cors);

    const system = `You are CodeMe, an expert frontend website generator. Create a complete, polished, responsive website using plain HTML, CSS and JavaScript only. Return ONLY valid JSON, no markdown fences, with this exact shape:
{"message":"short summary","files":[{"path":"index.html","content":"complete HTML"},{"path":"style.css","content":"CSS"},{"path":"script.js","content":"JavaScript"}]}
Always include index.html. Put CSS and JS in their separate files. Make the HTML reference style.css and script.js. Use accessible semantic HTML, mobile-first responsive design, working interactions where requested, and sensible placeholder content. Never claim you tested or deployed the site. Escape JSON strings correctly.`;

    try {
      const result = await env.AI.run(MODEL, {
        messages: [{ role: "system", content: system }, { role: "user", content: prompt }],
        max_tokens: 7000,
        temperature: 0.25
      });
      let content = result?.response || result?.output_text || "";
      if (Array.isArray(result?.choices)) content = result.choices[0]?.message?.content || content;
      if (!content) return out({ error: "The AI returned an empty response. Try a shorter prompt." }, 502, cors);
      content = content.replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "").trim();
      let data;
      try { data = JSON.parse(content); }
      catch {
        const start = content.indexOf("{"), end = content.lastIndexOf("}");
        if (start < 0 || end <= start) return out({ error: "AI response was not valid JSON. Try again." }, 502, cors);
        try { data = JSON.parse(content.slice(start, end + 1)); }
        catch { return out({ error: "AI response could not be parsed. Try a simpler prompt." }, 502, cors); }
      }
      if (!Array.isArray(data.files) || !data.files.some(f => String(f.path || "").toLowerCase().endsWith(".html")))
        return out({ error: "AI did not return an HTML file. Try again." }, 502, cors);

      const files = data.files.slice(0, 8).filter(f => {
        const path = String(f.path || "").replace(/\\/g, "/");
        return path && !path.startsWith("/") && !path.includes("..") && !path.startsWith(".");
      }).map(f => ({
        path: String(f.path).slice(0, 100),
        content: String(f.content || "").slice(0, 120000)
      }));
      return out({ message: data.message || "Website generated by CodeMe AI.", files }, 200, cors);
    } catch (e) {
      return out({ error: "AI request failed. Check your Workers AI binding and free usage limits." }, 502, cors);
    }
  }
};

function out(data, status, headers) {
  return new Response(JSON.stringify(data), {
    status,
    headers: { ...headers, "Content-Type": "application/json", "Cache-Control": "no-store" }
  });
}
